def build_provenance_context(
    db: sqlite3.Connection,
    txid: str,
    vout: int,
    price_at: Callable[[datetime.date], Decimal],
    current_price_eur: Decimal,
    as_of: datetime.date,
    max_depth: int = 100,
    evidence_root: str | Path | None = None,
    evidence_url_prefix: str = "",
    funding: dict[str, str] | None = None,
    trail: list[TrailCandidate] | None = None,
    saga_sources: SagaSources | None = None,
    max_nodes: int = 500,
    saga_document: SagaDocument | None = None,
) -> dict[str, object]:
    """Preformatted context dict for the all-parent, cross-domain saga."""
    from utxoproof.advisory import analyze_utxo
    from utxoproof.kyc import propagate_graph, seed_source_kyc

    seed_source_kyc(db)
    propagate_graph(db)
    document = saga_document or build_saga_document(
        db, txid, vout, price_at, saga_sources, max_depth, max_nodes
    )
    nodes = document.nodes
    if not nodes:
        raise ValueError(f"UTXO {txid}:{vout} not found")
    target = next(node for node in nodes if node.depth == 0)
    first = nodes[0]
    days_held = (as_of - first.block_time.date()).days
    current_value = target.amount_btc * current_price_eur
    advisory = analyze_utxo(
        txid,
        vout,
        target.amount_btc,
        first.block_time.date(),
        first.eur_value,
        current_value,
        target.kyc_status,
        target.kyc_fraction,
        as_of,
    )
    by_key = {(node.txid, node.vout): node for node in nodes}
    branches = _branch_rows(document, by_key)
    siblings = _sibling_rows(db, document)
    step_rows = _saga_step_rows(document, target)
    link_rows = [_link_row(link) for link in document.links]
    coverage_rows = [
        {
            "utxo": f"{row.txid}:{row.vout}",
            "share": f"{row.share:.2%}",
            "tier": row.tier or "unresolved",
        }
        for row in document.source_coverage
    ]
    evidence = _evidence_refs(document)
    return {
        "txid": txid,
        "vout": vout,
        "amount_btc": f"{target.amount_btc:.8f}",
        "current_value_eur": f"{current_value:.2f}",
        "current_price_eur": f"{current_price_eur:.2f}",
        "kyc_status": target.kyc_status,
        "kyc_fraction": f"{target.kyc_fraction:.0%}",
        "days_held": days_held,
        "flags": ",".join(sorted(f.value for f in advisory.flags)),
        "truncated": document.truncated_share > 0,
        "truncated_share": f"{document.truncated_share:.2%}",
        "max_depth": max_depth,
        "max_nodes": max_nodes,
        "coverage_pct": f"{document.coverage:.0%}",
        "coverage_share": f"{document.coverage:.4f}",
        "weakest_tier": document.weakest_tier or "—",
        "coverage_rows": coverage_rows,
        "steps": step_rows,
        "branches": branches,
        "siblings": siblings,
        "links": link_rows,
        "candidate_links": [row for row in link_rows if row["confidence"] == "candidate"],
        "evidence_links": [
            row for row in link_rows if row["confidence"] in ("exact", "approximate", "allocated")
        ],
        "unresolved": document.unresolved,
        "evidence": evidence,
        "prologue": _prologue_context({node.txid for node in nodes}, trail)
        if trail is not None
        else None,
        "attachments": _attachment_rows(
            db, [node.txid for node in nodes], evidence_root, evidence_url_prefix
        ),
    }


def _saga_step_rows(document: SagaDocument, target: SagaNode) -> list[dict[str, object]]:
    rows = []
    for number, node in enumerate(document.nodes, 1):
        attributed_btc = target.amount_btc * node.share
        rows.append(
            {
                "n": number,
                "date": node.block_time.date().isoformat(),
                "block": node.block_height if node.block_height is not None else "—",
                "event": node.event,
                "btc": f"{node.amount_btc:.8f}",
                "share": f"{node.share:.2%}",
                "attributed_btc": f"{attributed_btc:.8f}",
                "eur_price": f"{node.eur_price:.2f}",
                "eur_value": f"{node.eur_value:.2f}",
                "attributed_eur": f"{attributed_btc * node.eur_price:.2f}",
                "kyc": node.kyc_status,
                "evidence": node.evidence or f"{node.txid}:{node.vout}",
                "mixing": node.mixing_event,
                "source": node.is_source,
                "depth": node.depth,
            }
        )
    return rows


def _branch_rows(
    document: SagaDocument, by_key: dict[tuple[str, int], SagaNode]
) -> list[dict[str, object]]:
    rows = []
    for number, node in enumerate(document.nodes, 1):
        if len(node.parent_utxos) <= 1:
            continue
        for parent in node.parent_utxos:
            parent_node = by_key.get(parent)
            rows.append(
                {
                    "step": number,
                    "utxo": f"{parent[0]}:{parent[1]}",
                    "btc": (
                        f"{parent_node.amount_btc:.8f}" if parent_node is not None else "missing"
                    ),
                    "share": f"{parent_node.share:.2%}" if parent_node is not None else "—",
                    "kyc": parent_node.kyc_status if parent_node is not None else "unknown",
                }
            )
    return rows


def _sibling_rows(db: sqlite3.Connection, document: SagaDocument) -> list[dict[str, object]]:
    from utxoproof.provenance import db_get_output

    rows = []
    for number, node in enumerate(document.nodes, 1):
        for sibling in node.sibling_utxos:
            output = db_get_output(db, sibling[0], sibling[1])
            if output is None:
                continue
            rows.append(
                {
                    "step": number,
                    "utxo": f"{sibling[0]}:{sibling[1]}",
                    "btc": f"{Decimal(output['value_sat']) / Decimal(100_000_000):.8f}",
                    "kyc": output["kyc_status"],
                }
            )
    return rows


def _link_row(link: ProvenanceLink) -> dict[str, object]:
    return {
        "layer": link.layer,
        "confidence": link.confidence,
        "from": link.from_ref,
        "to": link.to_ref,
        "amount_eur": f"{link.amount_eur:,.2f}" if link.amount_eur is not None else "—",
        "amount_sat": f"{link.amount_sat:,}" if link.amount_sat is not None else "—",
        "evidence": link.evidence_ref,
        "note": link.note,
        "origin": link.origin,
    }


def _evidence_refs(document: SagaDocument) -> list[str]:
    refs: set[str] = set()
    for node in document.nodes:
        if node.evidence:
            refs.add(node.evidence)
    for link in document.links:
        refs.update(part.strip() for part in link.evidence_ref.split(";") if part.strip())
    return sorted(refs)


def _prologue_context(
    walked_txids: set[str], trail: list[TrailCandidate]
) -> list[dict[str, object]]:
    """Group trail candidates by funded chain tx for the walked steps only."""
    walked = walked_txids
    grouped: dict[str, list[TrailCandidate]] = {}
    for cand in trail:
        if cand.chain_txid not in walked:
            continue
        grouped.setdefault(cand.chain_txid, []).append(cand)
    result = []
    for chain_txid, cands in grouped.items():
        first = cands[0]
        items = []
        for cand in cands:
            if cand.bank is not None:
                bank_desc = (
                    f"{cand.bank.bank.date.isoformat()} {cand.bank.bank.description} "
                    f"{cand.bank.bank.amount_eur:,.2f} EUR "
                    f"(ref {cand.bank.bank.reference or '—'}) [{'; '.join(cand.bank.reasons)}]"
                )
            else:
                bank_desc = "no bank row matched this buy"
            items.append(
                {
                    "buy": (
                        f"{cand.buy_date} BUY {cand.buy_btc} BTC "
                        f"({cand.buy_fiat_eur} EUR, refid {cand.buy_refid})"
                    ),
                    "bank": bank_desc,
                }
            )
        result.append(
            {
                "chain_txid": chain_txid,
                "withdrawal_refid": first.withdrawal_refid,
                "withdrawal_date": first.withdrawal_date,
                "ledgers_file": first.ledgers_file,
                "bank_file": first.bank_file,
                "candidates": items,
                "hidden": first.hidden_count,
            }
        )
    return result


